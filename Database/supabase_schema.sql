CREATE POLICY "Allow public all access on laporan_masalah" ON laporan_masalah FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

ALTER TABLE validasi_ai ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all access on validasi_ai" ON validasi_ai FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

ALTER TABLE tindak_lanjut ENABLE ROW LEVEL SECURITY;
