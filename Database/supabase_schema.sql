-- ==============================================================================
-- SUPABASE DATABASE CONFIGURATION & SCHEMA (SEKITARNYA BEKASI)
-- Siap dijalankan langsung di menu: Supabase Dashboard -> SQL Editor -> Run
-- ==============================================================================

-- 1. BERSIHKAN TABEL & TIPE ENUM JIKA SUDAH ADA SEBELUMNYA
DROP TABLE IF EXISTS laporan_sistem CASCADE;
DROP TABLE IF EXISTS notifikasi CASCADE;
DROP TABLE IF EXISTS tindak_lanjut CASCADE;
DROP TABLE IF EXISTS validasi_ai CASCADE;
DROP TABLE IF EXISTS laporan_masalah CASCADE;
DROP TABLE IF EXISTS infrastruktur CASCADE;
DROP TABLE IF EXISTS users CASCADE;

DROP TYPE IF EXISTS role_enum CASCADE;
DROP TYPE IF EXISTS kategori_infrastruktur_enum CASCADE;
DROP TYPE IF EXISTS status_laporan_enum CASCADE;
DROP TYPE IF EXISTS status_validasi_enum CASCADE;

-- ------------------------------------------------------------------------------
-- 2. DEFINISI ENUM
-- ------------------------------------------------------------------------------
CREATE TYPE role_enum AS ENUM (
    'masyarakat', 
    'pemda', 
    'admin'
);

CREATE TYPE kategori_infrastruktur_enum AS ENUM (
    'jalan', 
    'jembatan', 
    'drainase', 
    'transportasi_publik', 
    'trotoar', 
    'penerangan_jalan', 
    'taman', 
    'lainnya'
);

CREATE TYPE status_laporan_enum AS ENUM (
    'menunggu_validasi', 
    'terverifikasi', 
    'dalam_tinjauan', 
    'sedang_dikerjakan', 
    'selesai', 
    'ditolak'
);

CREATE TYPE status_validasi_enum AS ENUM (
    'valid', 
    'akurasi_rendah', 
    'duplikat', 
    'anomali', 
    'tidak_valid'
);

-- ------------------------------------------------------------------------------
-- 3. TABEL: Users (Warga, Pemda, Admin)
-- ------------------------------------------------------------------------------
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(150) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    password VARCHAR(255) DEFAULT '$2a$12$defaultHashedCitizenPassword',
    no_telepon VARCHAR(25),
    domisili VARCHAR(100),
    role role_enum NOT NULL DEFAULT 'masyarakat',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ------------------------------------------------------------------------------
-- 4. TABEL: Infrastruktur (Fasilitas Publik Kota Bekasi)
-- ------------------------------------------------------------------------------
CREATE TABLE infrastruktur (
    infrastruktur_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_tempat VARCHAR(200) NOT NULL,
    kategori kategori_infrastruktur_enum NOT NULL,
    deskripsi TEXT,
    alamat TEXT,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    foto_url VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ------------------------------------------------------------------------------
-- 5. TABEL: Laporan_Masalah (Aspirasi & Masalah Fasilitas)
-- ------------------------------------------------------------------------------
CREATE TABLE laporan_masalah (
    laporan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    infrastruktur_id BIGINT REFERENCES infrastruktur(infrastruktur_id) ON DELETE SET NULL,
    judul_laporan VARCHAR(255) NOT NULL,
    deskripsi_masalah TEXT NOT NULL,
    foto_bukti VARCHAR(500),
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    status_laporan status_laporan_enum NOT NULL DEFAULT 'menunggu_validasi',
    is_spam BOOLEAN NOT NULL DEFAULT FALSE,
    tanggal_lapor TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ------------------------------------------------------------------------------
-- 6. TABEL: Validasi_AI (Verifikasi Cerdas Lokasi & Gambar)
-- ------------------------------------------------------------------------------
CREATE TABLE validasi_ai (
    validasi_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laporan_id BIGINT NOT NULL REFERENCES laporan_masalah(laporan_id) ON DELETE CASCADE,
    skor_akurasi_koordinat REAL NOT NULL,
    status_validasi status_validasi_enum NOT NULL DEFAULT 'valid',
    catatan_ai TEXT,
    waktu_validasi TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ------------------------------------------------------------------------------
-- 7. TABEL: Tindak_Lanjut (Balasan Resmi Pemda & Bukti Perbaikan)
-- ------------------------------------------------------------------------------
CREATE TABLE tindak_lanjut (
    tindak_lanjut_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laporan_id BIGINT NOT NULL REFERENCES laporan_masalah(laporan_id) ON DELETE CASCADE,
    pemda_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    keterangan_tindakan TEXT NOT NULL,
    foto_hasil_perbaikan VARCHAR(500),
    status_terbaru VARCHAR(100) NOT NULL,
    waktu_update TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ------------------------------------------------------------------------------
-- 8. TABEL: Notifikasi (Pemberitahuan Sistem bagi Pelapor)
-- ------------------------------------------------------------------------------
CREATE TABLE notifikasi (
    notifikasi_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    laporan_id BIGINT REFERENCES laporan_masalah(laporan_id) ON DELETE CASCADE,
    pesan TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    waktu_kirim TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ------------------------------------------------------------------------------
-- 9. TABEL: Laporan_Sistem (Kontak & Aduan Kendala Website ke Admin)
-- ------------------------------------------------------------------------------
CREATE TABLE laporan_sistem (
    kendala_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    nama_pelapor VARCHAR(150) NOT NULL,
    email_pelapor VARCHAR(150) NOT NULL,
    kategori_kendala VARCHAR(100) NOT NULL,
    pesan TEXT NOT NULL,
    status_kendala VARCHAR(50) NOT NULL DEFAULT 'menunggu_tinjauan',
    tanggapan_admin TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ------------------------------------------------------------------------------
-- 10. INDEXES FOR HIGH QUERY PERFORMANCE
-- ------------------------------------------------------------------------------
CREATE INDEX idx_laporan_user ON laporan_masalah(user_id);
CREATE INDEX idx_laporan_infrastruktur ON laporan_masalah(infrastruktur_id);
CREATE INDEX idx_laporan_spam ON laporan_masalah(is_spam);
CREATE INDEX idx_validasi_laporan ON validasi_ai(laporan_id);
CREATE INDEX idx_tindaklanjut_laporan ON tindak_lanjut(laporan_id);
CREATE INDEX idx_tindaklanjut_pemda ON tindak_lanjut(pemda_id);
CREATE INDEX idx_notifikasi_user ON notifikasi(user_id);
CREATE INDEX idx_notifikasi_laporan ON notifikasi(laporan_id);
CREATE INDEX idx_kendala_status ON laporan_sistem(status_kendala);

